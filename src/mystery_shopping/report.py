"""Build the Mystery Shopper Evaluation Report content from computed results (every number is computed)."""
from __future__ import annotations

import pandas as pd

from . import framework as F
from .report_render import to_markdown, to_pdf

DISCLAIMER = ("<b>All data in this report is synthetic.</b> It was generated by code in this repository to demonstrate mystery-shopping and "
              "customer-experience research methods. It does not describe any real court, judicial entity, staff member, customer, visit, "
              "recording or finding, and it is not an official or authorised client deliverable. 'The entity' refers to a hypothetical UAE "
              "judicial services provider.")

ACTIONS = {
    "Response time": "Set and publish channel service standards (e.g. social media first reply within 2 hours); add queue monitoring and staffing rules for peak periods.",
    "Communication quality": "Introduce bilingual (Arabic/English) response templates and plain-language guidance; review written replies for structure and accuracy.",
    "Professionalism": "Reinforce greeting, identification and impartiality standards through short refresher sessions and call/visit sampling.",
    "Information accuracy": "Create a single, version-controlled knowledge base of procedures, fees and document lists that all channels use; retrain on high-error scenarios.",
    "Resolution effectiveness": "Empower front-line staff to resolve common requests at first contact and define warm-transfer / referral paths with call-backs.",
    "Customer experience": "Improve wayfinding, IVR menus and accessibility support; collect real customer feedback after each interaction.",
}


def build_blocks(r: dict) -> list[tuple]:
    ch = r["ch"].set_index("channel")
    allc = ch.loc["All channels"]
    chans = ch.drop("All channels")
    best, worst = chans["sqi"].idxmax(), chans["sqi"].idxmin()
    rva = r["rva"].set_index("measure")
    gm = r["gap_matrix"]
    below = [(c, d, gm.loc[c, d]) for c in gm.index for d in gm.columns if gm.loc[c, d] < -10]
    below.sort(key=lambda x: x[2])
    waves = r["waves"]
    flagged = r["shop"][r["shop"]["flag"] != "Within range"]
    log = r["log"].set_index("rule")["rows_affected"]
    weakest_dims = r["dims"].mean().sort_values()
    rt = chans.sort_values("response_standard_met_pct")

    B: list[tuple] = [("h1", "1. Executive summary"), ("p", DISCLAIMER), ("bullets", [
        f"{int(allc['visits'])} mystery-shopping evaluations across five channels and two waves give an overall Service Quality Index (SQI) of "
        f"<b>{allc['sqi']:.0f}/100</b> (95% CI {allc['ci_low']:.0f}-{allc['ci_high']:.0f}), against a target of {F.TARGET_SCORE}. "
        f"{allc['visits_meeting_target_pct']:.0f}% of visits met the target.",
        f"<b>{best}</b> performs best (SQI {chans.loc[best, 'sqi']:.0f}) and <b>{worst}</b> weakest ({chans.loc[worst, 'sqi']:.0f}). "
        f"Only {', '.join(c for c in chans.index if chans.loc[c, 'sqi'] >= F.TARGET_SCORE) or 'no channel'} meets the target on average.",
        f"Registry outperforms ancillary services by {rva.loc['Service Quality Index', 'gap']:.0f} points (p < 0.001). The largest gap is in information "
        f"accuracy ({rva.loc['Information accuracy', 'registry']:.0f} vs {rva.loc['Information accuracy', 'ancillary']:.0f}).",
        f"Response standards are met least often on {rt.index[0].lower()} ({rt.iloc[0]['response_standard_met_pct']:.0f}% of contacts) and "
        f"{rt.index[1].lower()} ({rt.iloc[1]['response_standard_met_pct']:.0f}%).",
        f"Across channels, the weakest dimensions are {weakest_dims.index[0].lower()} ({weakest_dims.iloc[0]:.0f}) and {weakest_dims.index[1].lower()} ({weakest_dims.iloc[1]:.0f}). "
        f"First-contact resolution averages {allc['first_contact_resolution_pct']:.0f}%.",
        f"Consistency: {allc['critical_visits_pct']:.0f}% of visits scored below 60 (critical), and variability is highest on {chans['sqi_cv_pct'].idxmax().lower()} "
        f"(coefficient of variation {chans['sqi_cv_pct'].max():.0f}%). Wave-to-wave changes are positive on every channel, but none is statistically significant.",
        (f"Quality control flagged {len(flagged)} assessor(s) ({', '.join(flagged['shopper_id'])}) as scoring out of line with peers. Their scores "
         "should be re-calibrated before final reporting.") if len(flagged) else "No assessor was flagged in the calibration check.",
    ])]

    B += [("h1", "2. Objectives and scope"), ("bullets", [
        "Evaluate service delivery across email, telephone, social media, the registry counter and ancillary services (translation, notarisation, mediation information, visitor support).",
        "Score six service-quality dimensions: response time, communication quality, professionalism, information accuracy, resolution effectiveness and customer experience.",
        "Compare channels and the registry against ancillary services, identify service gaps and consistency issues, and recommend improvements.",
    ]), ("h1", "3. Methodology"), ("bullets", [
        "<b>Design:</b> trained mystery shoppers carry out scripted, realistic scenarios per channel (e.g. fee enquiries, document submission, hearing-date questions), "
        "spread across weekdays, mornings and afternoons, in two waves six months apart.",
        f"<b>Questionnaires:</b> {len(F.CRITERIA)} criteria, scored 2 (fully met), 1 (partly met) or 0 (not met). Each channel uses the criteria that apply to it "
        "(templates in questionnaires/). Response time is measured objectively against illustrative channel standards.",
        "<b>Scoring:</b> dimension score = mean criterion score rescaled to 0-100. SQI = weighted mean of the dimensions (information accuracy 25%, resolution 20%, "
        "and 15% each for response time, communication and professionalism, 10% customer experience).",
        "<b>Analysis:</b> means with 95% confidence intervals, Welch t-tests for registry vs ancillary and wave changes, coefficient of variation and share of critical visits "
        "for consistency, an assessor calibration check (residual z-scores), and a likelihood-to-recommend NPS as a proxy measure.",
        f"<b>Data quality:</b> {int(log['Rows in raw file'])} raw rows were cleaned to {int(log['Rows in clean dataset'])} valid visits using logged rules (duplicates, "
        "channel spellings, invalid scores, missing assessor IDs, date formats).",
    ])]

    B += [("pagebreak",), ("h1", "4. Channel performance"), ("img", r["figs"]["sqi_by_channel"]),
          ("table", r["ch"][["channel", "visits", "sqi", "ci_low", "ci_high", "visits_meeting_target_pct", "response_standard_met_pct", "first_contact_resolution_pct", "nps_demo"]]
           .rename(columns={"channel": "Channel", "visits": "Visits", "sqi": "SQI", "ci_low": "CI low", "ci_high": "CI high", "visits_meeting_target_pct": "≥ target %",
                            "response_standard_met_pct": "Resp. std %", "first_contact_resolution_pct": "FCR %", "nps_demo": "NPS (demo)"}), None),
          ("img", r["figs"]["dimension_heatmap"]),
          ("p", "Dimension scores more than 10 points below target: " + "; ".join(f"{c} / {d.lower()} ({gm.loc[c, d] + F.TARGET_SCORE:.0f})" for c, d, _ in below[:8]) + "."),
          ("img", r["figs"]["response_standard"])]

    B += [("pagebreak",), ("h1", "5. Registry vs ancillary services"), ("img", r["figs"]["registry_vs_ancillary"]),
          ("table", r["rva"].rename(columns={"measure": "Measure", "registry": "Registry", "ancillary": "Ancillary", "gap": "Gap", "cohens_d": "Effect size (d)", "p_value": "p", "significant_5pct": "Sig."}), None),
          ("p", f"Every dimension favours the registry. The information-accuracy gap is large (effect size d = {rva.loc['Information accuracy', 'cohens_d']:.1f}), "
                "which suggests ancillary staff lack an up-to-date reference for procedures and fees rather than a courtesy problem: professionalism shows the smallest gap.")]

    B += [("pagebreak",), ("h1", "6. Service gaps and consistency"), ("img", r["figs"]["top_gaps"]), ("img", r["figs"]["consistency"]),
          ("table", r["ch"][["channel", "sqi_sd", "sqi_cv_pct", "critical_visits_pct"]].rename(columns={"channel": "Channel", "sqi_sd": "SD", "sqi_cv_pct": "CV %", "critical_visits_pct": "Critical (<60) %"}), None),
          ("img", r["figs"]["wave_comparison"]),
          ("table", waves.rename(columns={"channel": "Channel", "wave_1": "Wave 1", "wave_2": "Wave 2", "change": "Change", "p_value": "p", "significant_5pct": "Sig."}), None),
          ("p", f"Afternoon visits score lower than morning visits on average ({'significant' if r['tod_p'] < 0.05 else 'not significant'}, p = {r['tod_p']:.3f}). "
                "This points to staffing or fatigue effects worth checking against queue data."),
          ("img", r["figs"]["shopper_calibration"])]

    B += [("pagebreak",), ("h1", "7. Likelihood to recommend (NPS demonstration)"), ("img", r["figs"]["nps_demo"]),
          ("p", "Shoppers rated how likely they would be to recommend the service after each visit. Because the raters are trained assessors, this is a "
                "proxy indicator that tracks the SQI. It is not a substitute for a real customer NPS, which should be collected from actual service users.")]

    B += [("h1", "8. Recommendations"), ("bullets",
          [f"<b>{d} (cross-channel score {weakest_dims[d]:.0f}):</b> {ACTIONS[d]}" for d in weakest_dims.index[:3]] + [
              f"<b>Prioritise {worst.lower()}:</b> it has the lowest SQI and the most critical visits. Assign an owner and track a monthly target.",
              "<b>Close the registry-ancillary gap:</b> give ancillary services the same knowledge base, scripts and supervision as the registry.",
              "<b>Improve consistency:</b> publish service standards per channel, run monthly call and visit sampling, and coach staff on the lowest-scoring criteria.",
              "<b>Strengthen the programme:</b> re-calibrate flagged assessors, keep scenarios identical between waves, and add a real customer-feedback survey.",
          ])]
    B += [("h1", "9. Limitations"), ("bullets", [
        "All observations are synthetic and generated from documented assumptions (docs/synthetic_data_design.md). Patterns such as the registry outperforming ancillary services were built in on purpose to demonstrate the analysis.",
        "Service standards and dimension weights are illustrative choices. A real programme would agree them with the client.",
        "About 60 visits per channel per wave can detect gaps of roughly 6-8 SQI points. Smaller wave-to-wave changes need more visits or a longer time series.",
        "Mystery shopping measures a scripted experience. It should be combined with real customer feedback and operational data.",
    ]), ("pagebreak",), ("h1", "Appendix: cleaning log"), ("table", r["log"].rename(columns={"rule": "Rule", "rows_affected": "Rows", "action": "Action"}), [8.4, 1.6, 7.0])]
    return B


def write_reports(r: dict):
    F.REPORTS.mkdir(parents=True, exist_ok=True)
    blocks = build_blocks(r)
    md, pdf = F.REPORTS / "mystery_shopper_evaluation_report.md", F.REPORTS / "mystery_shopper_evaluation_report.pdf"
    to_markdown(blocks, md)
    to_pdf(blocks, pdf)
    return md, pdf
